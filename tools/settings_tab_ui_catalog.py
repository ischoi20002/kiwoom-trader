def build_key_to_ui_row() -> dict[str, SettingUiRow]:
    """param_key → 첫 매핑(중복 키 없어야 함)."""
    m: dict[str, SettingUiRow] = {}
    for row in SETTING_UI_ROWS:
        if row.param_key in m:
            raise ValueError(f"중복 UI 카탈로그 키: {row.param_key}")
        m[row.param_key] = row
    return m


KEY_TO_UI_ROW: dict[str, SettingUiRow] = build_key_to_ui_row()
